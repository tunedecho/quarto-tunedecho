#!/usr/bin/env python3
"""Generate the Quarto brand file and the per-engine token files from the
design system's tokens.json.

Writes:
  _extensions/tunedecho/_brand.yml        Quarto brand file (colors, fonts, logos)
  _extensions/tunedecho/typst/tokens.typ  Typst constants (colors, key strip, fonts)
  _extensions/tunedecho/html/tokens.scss  SCSS variables (colors, fonts)
  _extensions/tunedecho/html/_assets.scss marks as data URIs for CSS (wordmark, seal)
  _extensions/tunedecho/html/tokens.css   copy of the design system's tokens.css
  _extensions/tunedecho/html/components.css  copy of components/bundle.css

Run from the repository root:  python3 tools/brand-from-tokens.py
Standard library only.
"""

import base64
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DS = ROOT / "tuned-echo-design-system"
EXT = ROOT / "_extensions" / "tunedecho"

KEY_ORDER = ["key-pink", "key-orange", "key-yellow", "key-green", "key-blue", "key-purple", "key-ink"]

# Document type choices made on top of the design system (see plan.md, 2026-10-13).
# The design system's sans stays for small text: contact block, footers, running
# heads, captions. Running text in documents uses BODY_FAMILY; ALT_FAMILY sets the
# section headings and is the sans alternative for body text (`mainfont: Figtree`).
BODY_FAMILY = "Newsreader"
BODY_STACK = 'Newsreader, "Iowan Old Style", Georgia, serif'
ALT_FAMILY = "Figtree"
# Section headings inside documents: ALT_FAMILY at regular weight.
HEADING_STACK = 'Figtree, "Helvetica Neue", Arial, sans-serif'

# Font files shipped in _extensions/tunedecho/fonts (family, file, weight, style)
FONT_FILES = [
    ("Instrument Serif", "InstrumentSerif-Regular.ttf", 400, "normal"),
    ("Instrument Serif", "InstrumentSerif-Italic.ttf", 400, "italic"),
    ("Plus Jakarta Sans", "PlusJakartaSans-Regular.ttf", 400, "normal"),
    ("Plus Jakarta Sans", "PlusJakartaSans-Italic.ttf", 400, "italic"),
    ("Plus Jakarta Sans", "PlusJakartaSans-Medium.ttf", 500, "normal"),
    ("Plus Jakarta Sans", "PlusJakartaSans-MediumItalic.ttf", 500, "italic"),
    ("Plus Jakarta Sans", "PlusJakartaSans-SemiBold.ttf", 600, "normal"),
    ("Plus Jakarta Sans", "PlusJakartaSans-SemiBoldItalic.ttf", 600, "italic"),
    ("Newsreader", "Newsreader-Regular.ttf", 400, "normal"),
    ("Newsreader", "Newsreader-Italic.ttf", 400, "italic"),
    ("Newsreader", "Newsreader-SemiBold.ttf", 600, "normal"),
    ("Figtree", "Figtree-Regular.ttf", 400, "normal"),
    ("Figtree", "Figtree-Italic.ttf", 400, "italic"),
    ("Figtree", "Figtree-SemiBold.ttf", 600, "normal"),
    ("Oswald", "Oswald-Regular.ttf", 400, "normal"),
    ("Oswald", "Oswald-Medium.ttf", 500, "normal"),
]

LOGOS = {
    "wordmark": ("wordmark.png", "Tuned Echo wordmark with key strip"),
    "wordmark-motto": ("wordmark-motto.png", "Tuned Echo wordmark with motto"),
    "wordmark-reversed": ("wordmark-reversed.png", "Tuned Echo wordmark, reversed"),
    "seal": ("seal.png", "Tuned Echo seal"),
    "seal-reversed": ("seal-reversed.png", "Tuned Echo seal, reversed"),
}


def load_tokens():
    with open(DS / "tokens.json") as f:
        return json.load(f)


def resolve_colors(tokens):
    """Return {name: {"light": hex, "dark": hex}} with {ref} values resolved."""
    raw = {}
    for t in tokens["color"]["tokens"]:
        v = t["value"]
        raw[t["name"]] = v if isinstance(v, dict) else {"light": v, "dark": v}

    def resolve(name, theme, seen=()):
        v = raw[name][theme]
        m = re.fullmatch(r"\{(.+)\}", v)
        if m:
            ref = m.group(1)
            if ref in seen:
                sys.exit(f"circular color reference: {name}")
            return resolve(ref, theme, seen + (name,))
        return v

    return {n: {th: resolve(n, th) for th in ("light", "dark")} for n in raw}


def family_name(stack):
    """First family of a CSS font stack, unquoted."""
    return stack.split(",")[0].strip().strip('"').strip("'")


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(f"wrote {path.relative_to(ROOT)}")


def gen_brand(tokens, colors):
    fam = {k: family_name(v) for k, v in tokens["type"]["families"].items()}
    lines = [
        "# Generated by tools/brand-from-tokens.py from tuned-echo-design-system/tokens.json.",
        "# Do not edit by hand; edit tokens.json and rerun the script.",
        "",
        "meta:",
        "  name:",
        "    short: Tuned Echo",
        "    full: Tuned Echo Systems LLC",
        "  link:",
        "    home: https://tunedecho.com",
        "",
        "color:",
        "  palette:",
    ]
    for name, v in colors.items():
        lines.append(f'    {name}: "{v["light"]}"')
    for name, v in colors.items():
        if v["light"] != v["dark"]:
            lines.append(f'    {name}-dark: "{v["dark"]}"')
    lines += [
        "  foreground: text",
        "  background: bg",
        "  primary: ink",
        "  secondary: muted",
        "  light: paper",
        "  dark: ink",
        "",
        "typography:",
        "  fonts:",
    ]
    for family in (fam["serif"], BODY_FAMILY, fam["sans"], ALT_FAMILY, fam["cond"]):
        lines += [f"    - family: {family}", "      source: file", "      files:"]
        for f, file, weight, style in FONT_FILES:
            if f == family:
                lines += [
                    f"        - path: fonts/{file}",
                    f"          weight: {weight}",
                    f"          style: {style}",
                ]
    lines += [
        "  base:",
        f"    family: {BODY_FAMILY}",
        "    line-height: 1.5",
        "  headings:",
        f"    family: {fam['serif']}",
        "    weight: 400",
        "    color: ink",
        "  link:",
        "    color: ink",
        "    decoration: underline",
        "",
        "logo:",
        "  images:",
    ]
    for key, (file, alt) in LOGOS.items():
        lines += [f"    {key}:", f"      path: assets/{file}", f"      alt: {alt}"]
    lines += [
        "  small:",
        "    light: seal",
        "    dark: seal-reversed",
        "  medium:",
        "    light: wordmark",
        "    dark: wordmark-reversed",
        "  large: wordmark-motto",
        "",
    ]
    write(EXT / "_brand.yml", "\n".join(lines))


def gen_typst(tokens, colors):
    fam = {k: family_name(v) for k, v in tokens["type"]["families"].items()}
    out = [
        "// Generated by tools/brand-from-tokens.py from tuned-echo-design-system/tokens.json.",
        "// Do not edit by hand.",
        "",
        "#let te-light = (",
    ]
    for name, v in colors.items():
        out.append(f'  "{name}": rgb("{v["light"]}"),')
    out += [")", "", "#let te-dark = ("]
    for name, v in colors.items():
        out.append(f'  "{name}": rgb("{v["dark"]}"),')
    out += [")", ""]
    out.append("// Key strip order. Never reorder.")
    out.append("#let te-key-order = (" + ", ".join(f'"{k}"' for k in KEY_ORDER) + ")")
    out += [
        "",
        "#let te-fonts = (",
        f'  serif: "{fam["serif"]}",',
        f'  body: "{BODY_FAMILY}",',
        f'  heading: "{ALT_FAMILY}",',
        f'  sans: "{fam["sans"]}",',
        f'  cond: "{fam["cond"]}",',
        '  mono: ("Menlo", "DejaVu Sans Mono"),',
        ")",
        "",
    ]
    write(EXT / "typst" / "tokens.typ", "\n".join(out))


def gen_scss(tokens, colors):
    fams = tokens["type"]["families"]
    out = [
        "/*-- scss:defaults --*/",
        "// Generated by tools/brand-from-tokens.py from tuned-echo-design-system/tokens.json.",
        "// Do not edit by hand. Listed as the last theme layer so these come first.",
        "",
    ]
    for name, v in colors.items():
        out.append(f"$te-{name}: {v['light']} !default;")
    out.append("")
    for name, v in colors.items():
        if v["light"] != v["dark"]:
            out.append(f"$te-{name}-dark: {v['dark']} !default;")
    out += [
        "",
        "$te-key-colors: (" + ", ".join(f"${'te-' + k}" for k in KEY_ORDER if k != "key-ink") + ") !default;",
        "",
    ]
    for group in ("spacing", "radius", "layout"):
        for t in tokens[group]["tokens"]:
            out.append(f"$te-{t['name']}: {t['value']} !default;")
    out += [
        "",
        f"$te-font-serif: {fams['serif']} !default;",
        f"$te-font-body: {BODY_STACK} !default;",
        f"$te-font-heading: {HEADING_STACK} !default;",
        f"$te-font-sans: {fams['sans']} !default;",
        f"$te-font-cond: {fams['cond']} !default;",
        '$te-font-mono: "SF Mono", Menlo, "DejaVu Sans Mono", "Liberation Mono", monospace !default;',
        "",
    ]
    write(EXT / "html" / "tokens.scss", "\n".join(out))


def gen_assets_scss():
    out = [
        "// Generated by tools/brand-from-tokens.py: the marks as data URIs, so CSS can",
        "// place them without depending on file paths. Do not edit by hand.",
        "",
    ]
    for key, (file, _alt) in LOGOS.items():
        data = base64.b64encode((EXT / "assets" / file).read_bytes()).decode()
        out.append(f'$te-{key}-data: url("data:image/png;base64,{data}") !default;')
    out.append("")
    write(EXT / "html" / "_assets.scss", "\n".join(out))


def copy_css():
    for src, dst in (
        (DS / "tokens.css", EXT / "html" / "tokens.css"),
        (DS / "components" / "bundle.css", EXT / "html" / "components.css"),
    ):
        shutil.copyfile(src, dst)
        print(f"copied {dst.relative_to(ROOT)}")


def main():
    tokens = load_tokens()
    colors = resolve_colors(tokens)
    gen_brand(tokens, colors)
    gen_typst(tokens, colors)
    gen_scss(tokens, colors)
    gen_assets_scss()
    copy_css()


if __name__ == "__main__":
    main()
